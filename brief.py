def candidates(data, pool=0):
    """LLM 에 넘길 후보 풀을 만든다. (기계는 '자를 수 있는 것'만 자른다)

    [설계 변경 2026-07-31]
      예전엔 여기서 카테고리당 2건씩 기계적으로 13건을 확정해 LLM 에 넘겼다.
      그런데 '무엇을 실을 것인가'는 의미 판단이라 키워드 점수보다 LLM 이 낫다.
      실측 근거: 키워드로는 영원히 못 잡는 제목이 있다.
        "'빗장 vs 개방' 中 AI·칩 공습에 갈라진 美"  -> 정책 키워드 0개라 2점
      반대로 LLM 큐레이션이 매긴 임팩트 점수는 이 파이프라인 최고의 신호였다.
      그래서 최종 선별을 LLM 으로 옮기고, 여기서는 후보를 넓게 넘긴다.

    기계가 여전히 책임지는 것(LLM 에게 맡기면 안 되는 것):
      - 링크 없는 항목 제외 (브리프는 원문보기 링크가 필수)
      - 링크·매체·발행일의 정확성 (refine 단계에서 4겹 검증 완료)

    영문 항목도 넘긴다. refine 이 '국문이 있으면 영문 멤버를 버리는' 정책을 이미
    적용하므로, 여기 남은 영문 대표는 국내 미보도 글로벌 이슈다. 실제 사람 브리프
    (07-30)는 12건 중 절반이 영문이었다. 예전 필터는 이걸 통째로 막고 있었다.
    """
    items = [x for x in data["items"] if x.get("url")]
    items.sort(key=lambda r: -r["score"])
    if pool:
        items = items[:pool]
    own = [x for x in (data.get("own_track") or []) if x.get("url")]
    # 구제 후보: 컷 밖이지만 링크를 가진 저점 항목(refine 이 생성).
    # 기계 점수가 낮아도 사안이 중요한 기사를 LLM 이 건져낼 수 있게 한다.
    rescue = [x for x in (data.get("rescue") or []) if x.get("url")]
    return items, own, rescue


def drop_prev_sent(day, pool, own, rescue):
    """직전에 사람이 발송한 브리프에 이미 실린 사건을 후보에서 뺀다.

    [주의] 자르는 순서가 중요하다. candidates() 의 pool 상한을 적용한 '뒤'에
    빼면 그만큼 후보가 줄어든다. 여기서는 상한 적용 후에 빼되, 빠진 자리를
    메우지는 않는다 - 어제 나간 기사가 상위를 차지했다는 건 그 자리가
    원래 낭비되고 있었다는 뜻이므로 후보 수가 줄어드는 게 정상이다.
    """
    try:
        sys.path.insert(0, os.path.join(BASE, "cowork"))
        from dedup_prev import PrevFilter, render_dropped
    except Exception:
        return pool, own, rescue, [], None, None
    f = PrevFilter(day)
    if not f.active:
        return pool, own, rescue, [], None, None
    pool, d1 = f.split(pool)
    own, d2 = f.split(own)
    rescue, d3 = f.split(rescue)
    dropped = d1 + d2 + d3
    return pool, own, rescue, dropped, f.day, render_dropped


