CASEBOOK = os.path.join(BASE, "docs", "사례집.md")
REJECTED = os.path.join(BASE, "config", "rejected.jsonl")


def _norm_head(h):
    return re.sub(r"[^가-힣A-Za-z0-9]", "", (h or ""))[:24]


def load_cases(path=CASEBOOK):
    """docs/사례집.md 의 표를 읽는다. | 날짜 | 판정 | 헤드라인 | 이유 | 일반화 |"""
    rows = []
    if not os.path.exists(path):
        return rows
    for line in open(path, encoding="utf-8"):
        if not line.startswith("| 20"):
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) < 5:
            continue
        date, kind, head, why, gen = c[0], c[1], c[2], c[3], c[4]
        # 사유가 아직 안 들어온 자리표시 행은 버린다(나중에 진짜 사유 행이 따로 들어온다)
        if "사유 미제시" in why or why.startswith("(소급"):
            continue
        rows.append({"date": date, "kind": kind, "head": head,
                     "why": why, "gen": gen})
    return rows


def load_rejected(path=REJECTED):
    rows = []
    if not os.path.exists(path):
        return rows
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        try:
            d = json.loads(line)
        except ValueError:
            continue
        why = (d.get("reason") or "").strip()
        # [2026-09-22] '(추정)' 으로 시작하는 건은 사용자가 말한 사유가 아니라
        #   repeat_gate 가 "상위 rank 인데 발송본에 없다"고 짐작해 적은 것이다.
        #   사용자 말이 아닌 것을 사용자 사례로 프롬프트에 넣으면 안 된다.
        if why and not why.startswith(("(추정)", "(소급)")):
            rows.append(d)
    return rows


def render_cases(cases=None, rejected=None):
    """판정 직전에 읽는 사례 블록. H 절보다 최신이므로 충돌 시 이쪽이 이긴다.

    [왜] H 절(평가 원문 105건)은 2026-08-10~08-26 에서 멈춰 있다. 9월 들어
      사용자가 발송본을 고치며 남긴 사유는 docs/사례집.md 와
      config/rejected.jsonl 에만 쌓였고 **프롬프트에는 한 줄도 없었다.**
      실측 09-22: 판정사유 557건 중 '사례집' 언급 0건. 지침은 "판정 직전에
      규칙표 대신 사례집을 읽는다"고 하는데, 읽을 문서에 없었다.

    [읽는 법] 규칙으로 쓰지 말 것. 오늘 후보 하나를 놓고 **"이 사례들 중
      어느 쪽에 가까운가"** 를 묻는다. 조건이 맞는 규칙을 찾는 것이 아니다.
    """
    cases = load_cases() if cases is None else cases
    rejected = load_rejected() if rejected is None else rejected
    if not cases and not rejected:
        return []

    L = []
    L.append("**I. 편집자 수정 사례집 - H 보다 최신입니다. 충돌하면 이쪽을 따르세요**")
    L.append("  사용자가 발송본을 고칠 때마다 '뺀 것 / 넣은 것 + 그가 말한 이유'를")
    L.append("  그대로 쌓은 것입니다. **규칙표가 아닙니다.** 오늘 후보 하나를 놓고")
