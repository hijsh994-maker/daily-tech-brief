def load(path=RATINGS):
    out = []
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    out.append(json.loads(line))
    except Exception:
        return []
    return out


def _avg(rows):
    """평균 등급(0~2). 표본이 적어 소수점 한 자리까지만 본다."""
    v = [RANK[r["rating"]] for r in rows if r.get("rating") in RANK]
    return (sum(v) / float(len(v))) if v else None


def _bucket(rows, key):
    d = defaultdict(list)
    for r in rows:
        k = r.get(key)
        if k:
            d[k].append(r)
    return d


